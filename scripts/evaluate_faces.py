"""Evaluate face recognition on a labelled folder.

    python scripts/evaluate_faces.py --root eval_data --fixed-threshold 0.45
    python scripts/evaluate_faces.py --root class_data/photos --perturb   # one photo per identity

Layout:  <root>/<identity>/*.jpg.   With --perturb and flat photos (<root>/*.jpg) each
photo is its own identity and extra "probe" images are generated by SYNTHETIC perturbations
(brightness, blur, downscale, rotation). Those numbers measure robustness to degradations
only; they are NOT a substitute for real, consented, multi-session classroom data.
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image, ImageEnhance, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from evaluation.face_eval import run, to_json  # noqa: E402
from src.pipelines.face_pipeline import get_face_embeddings  # noqa: E402

EXTS = {".jpg", ".jpeg", ".png"}
PERTURBATIONS = {
    "dark": lambda im: ImageEnhance.Brightness(im).enhance(0.45),
    "bright": lambda im: ImageEnhance.Brightness(im).enhance(1.6),
    "blur": lambda im: im.filter(ImageFilter.GaussianBlur(2.0)),
    "lowres": lambda im: im.resize((max(24, im.width // 3), max(24, im.height // 3))).resize(im.size),
    "tilt10": lambda im: im.rotate(10, expand=False, fillcolor=(0, 0, 0)),
}


def load(root: Path, perturb: bool):
    data, failures, times = {}, [], []
    folders = [p for p in sorted(root.iterdir()) if p.is_dir()]
    if folders:
        groups = {p.name: sorted(f for f in p.iterdir() if f.suffix.lower() in EXTS) for p in folders}
    else:
        groups = {f.stem: [f] for f in sorted(root.iterdir()) if f.suffix.lower() in EXTS}
    for ident, files in groups.items():
        embs = []
        for f in files:
            variants = [Image.open(f).convert("RGB")]
            if perturb:
                variants += [fn(variants[0]) for fn in PERTURBATIONS.values()]
            for k, im in enumerate(variants):
                t = time.perf_counter()
                e = get_face_embeddings(im)
                times.append(time.perf_counter() - t)
                if len(e) == 1:
                    embs.append(e[0])
                elif k == 0:
                    failures.append(f"{f.name}: {len(e)} faces")
        if embs:
            data[ident] = np.array(embs)
    return data, failures, times


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--perturb", action="store_true")
    ap.add_argument("--target-far", type=float, default=0.01)
    ap.add_argument("--margin", type=float, default=0.05)
    ap.add_argument("--fixed-threshold", type=float, default=0.45)
    ap.add_argument("--out")
    a = ap.parse_args()
    data, failures, times = load(Path(a.root), a.perturb)
    report = run(data, a.target_far, a.margin, fixed_threshold=a.fixed_threshold)
    report.update(images_embedded=len(times), enrolment_failures=failures, mean_seconds_per_image=round(float(np.mean(times)), 3) if times else None,
                  synthetic_perturbation=bool(a.perturb))
    text = to_json(report)
    print(text)
    if a.out:
        Path(a.out).write_text(text)


if __name__ == "__main__":
    main()
